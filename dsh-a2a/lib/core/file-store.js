/**
 * Where a group's attachments actually live.
 *
 * WHY NOT IN THE FEED
 *
 * `groups.json` is one document rewritten in full on every post. Putting a 3 MiB
 * image in it would make every subsequent message cost 3 MiB of disk and of fsync —
 * the comment above `MAX_PAYLOAD_BYTES` in `groups.js` has said this since before any
 * of it was implemented. So attachments live as files beside the store, and the feed
 * carries a reference: `{ fileId, name, size, sha256, mime }`.
 *
 * THREE RULES THAT ARE NOT NEGOTIABLE
 *
 * 1. **The file id is chosen by the host, never by the caller.** A caller-supplied id
 *    is a path-traversal primitive: `../../groups.json` is a valid id string. Ids are
 *    `f-` + random, and nothing else ever reaches `join()`.
 * 2. **`name` is display text and never touches the filesystem.** Two members may both
 *    send `报告.pdf`; the disk holds them apart by id, and the name only appears in the
 *    feed.
 * 3. **A file is not usable until its digest checks out.** Uploading is not publishing:
 *    chunks land in a staging area, and only a completed upload whose sha256 matches
 *    what the sender promised becomes visible to anybody.
 *
 * @module dsh-a2a/file-store
 */

import { createHash, randomUUID } from 'node:crypto';
import { createReadStream, createWriteStream } from 'node:fs';
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  renameSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { join } from 'node:path';

/** Largest single file a group may hold. */
export const MAX_FILE_BYTES = 10 * 1024 * 1024;

/** Largest single chunk a caller may send. Base64 inflates by ~33%, so this is 341 KiB on the wire. */
export const MAX_CHUNK_BYTES = 256 * 1024;

/** Most bytes a group's files may occupy. */
export const MAX_GROUP_FILE_BYTES = 200 * 1024 * 1024;

/** Longest display name. Not a path, so only the UI cares. */
export const MAX_FILE_NAME_CHARS = 200;

/** An error whose `code` is stable enough for a tool result to branch on. */
function fileError(code, message, details) {
  const error = new Error(message);
  error.code = code;
  error.details = details ?? {};
  return error;
}

/** Whether a value looks like a host-issued id and cannot escape a directory. */
export function isFileId(value) {
  return typeof value === 'string' && /^f-[A-Za-z0-9_-]{16,}$/u.test(value);
}

/**
 * Build the file store over one directory.
 *
 * @param {object} options - `{ directory, logger, clock }`.
 * @returns {object} the store.
 */
export function createFileStore({ directory, logger, clock } = {}) {
  const root = join(directory, 'files');
  const now = typeof clock === 'function' ? clock : Date.now;
  /** Uploads in progress: fileId → { groupId, name, size, sha256, mime, chunks, received, uploadedBy }. */
  const pending = new Map();

  const groupDirectory = (groupId) => join(root, sealSegment(groupId));
  const stagingDirectory = (groupId) => join(groupDirectory(groupId), '.staging');
  const objectPath = (groupId, fileId) => join(groupDirectory(groupId), fileId);
  const partPath = (groupId, fileId, index) => join(stagingDirectory(groupId), `${fileId}.p${index}`);

  /** Make sure a directory exists. */
  function ensure(directory) {
    mkdirSync(directory, { recursive: true, mode: 0o700 });
  }

  /**
   * Turn an arbitrary id into one directory segment.
   *
   * Group ids are generated by the store, but they arrive here from a skill payload, and a
   * payload is attacker-controlled by definition. Everything outside `[A-Za-z0-9_-]` becomes
   * `_`, which makes `..` unable to climb and `/` unable to nest.
   */
  function sealSegment(value) {
    return String(value).replace(/[^A-Za-z0-9_-]/gu, '_');
  }

  /** Bytes already used by this group, from the objects on disk. */
  function usage(groupId) {
    const directory = groupDirectory(groupId);
    if (!existsSync(directory)) return 0;
    let total = 0;
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      if (!entry.isFile()) continue;
      if (!isFileId(entry.name)) continue;
      try {
        total += statSync(join(directory, entry.name)).size;
      } catch {
        // A file that vanished between listing and stat contributes nothing.
      }
    }
    return total;
  }

  /**
   * Open an upload. Nothing becomes visible until {@link finishUpload} succeeds.
   *
   * @param {object} input - declared file facts.
   * @returns {{fileId: string, chunkSize: number, chunks: number}} what the sender must now send.
   */
  function beginUpload(input = {}) {
    const groupId = sealSegment(input.groupId);
    const size = Number(input.size);
    if (!Number.isInteger(size) || size <= 0) throw fileError('bad_file_size', '文件大小必须是正整数。');
    if (size > MAX_FILE_BYTES) {
      throw fileError('file_too_large', `单个文件最大 ${Math.round(MAX_FILE_BYTES / 1024 / 1024)} MiB。`, { max: MAX_FILE_BYTES, size });
    }
    const name = typeof input.name === 'string' && input.name.trim() !== '' ? input.name.trim() : '';
    if (name === '') throw fileError('bad_file_name', '文件需要一个名字，用于在消息里显示。');
    if (name.length > MAX_FILE_NAME_CHARS) throw fileError('bad_file_name', `文件名最多 ${MAX_FILE_NAME_CHARS} 字。`);
    const sha256 = typeof input.sha256 === 'string' ? input.sha256.toLowerCase() : '';
    if (!/^[0-9a-f]{64}$/u.test(sha256)) throw fileError('bad_digest', '必须提供文件的 sha256（64 位十六进制）。');

    const already = usage(groupId);
    if (already + size > MAX_GROUP_FILE_BYTES) {
      throw fileError(
        'quota_exceeded',
        `本群附件空间已用 ${Math.round(already / 1024 / 1024)} MiB，上限 ${Math.round(MAX_GROUP_FILE_BYTES / 1024 / 1024)} MiB。`,
        { used: already, max: MAX_GROUP_FILE_BYTES },
      );
    }

    const chunks = Math.max(1, Math.ceil(size / MAX_CHUNK_BYTES));
    const fileId = `f-${randomUUID().replace(/-/gu, '')}`;
    pending.set(fileId, {
      groupId,
      name,
      size,
      sha256,
      mime: typeof input.mime === 'string' && input.mime !== '' ? input.mime : 'application/octet-stream',
      chunks,
      received: new Set(),
      uploadedBy: input.uploadedBy ?? '',
      startedAt: now(),
    });
    ensure(stagingDirectory(groupId));
    logger?.info?.('file upload opened', { groupId, fileId, size, chunks });
    return { fileId, chunkSize: MAX_CHUNK_BYTES, chunks };
  }

  /**
   * Accept one chunk.
   *
   * Chunks may arrive in any order and may be retried; the same index overwrites itself, which
   * is what makes a retried request harmless rather than a corruption.
   */
  function putChunk(input = {}) {
    const fileId = String(input.fileId ?? '');
    const upload = pending.get(fileId);
    if (upload === undefined) {
      throw fileError('upload_unknown', '没有这个上传会话：可能已过期，或宿主重启了，请重新开始上传。', { fileId });
    }
    const index = Number(input.index);
    if (!Number.isInteger(index) || index < 0 || index >= upload.chunks) {
      throw fileError('bad_chunk_index', `分块序号必须在 0..${upload.chunks - 1} 之间。`, { index, chunks: upload.chunks });
    }
    const base64 = typeof input.data === 'string' ? input.data : '';
    if (base64 === '') throw fileError('bad_chunk', '分块内容为空。');
    let buffer;
    try {
      buffer = Buffer.from(base64, 'base64');
    } catch {
      throw fileError('bad_chunk', '分块不是合法的 base64。');
    }
    if (buffer.length > MAX_CHUNK_BYTES) {
      throw fileError('chunk_too_large', `单块最大 ${MAX_CHUNK_BYTES} 字节。`, { max: MAX_CHUNK_BYTES, size: buffer.length });
    }
    writeFileSync(partPath(upload.groupId, fileId, index), buffer, { mode: 0o600 });
    upload.received.add(index);
    return { fileId, index, received: upload.received.size, total: upload.chunks };
  }

  /**
   * Complete an upload: verify the digest, then publish.
   *
   * The order matters. Concatenating first and checking afterwards would leave a bad object on
   * disk for the window between the two; checking the digest over the assembled bytes and only
   * then renaming is what keeps "visible" and "verified" the same instant.
   */
  async function finishUpload(input = {}) {
    const fileId = String(input.fileId ?? '');
    const upload = pending.get(fileId);
    if (upload === undefined) {
      throw fileError('upload_unknown', '没有这个上传会话：可能已过期，或宿主重启了，请重新开始上传。', { fileId });
    }
    if (upload.received.size !== upload.chunks) {
      throw fileError(
        'upload_incomplete',
        `还有 ${upload.chunks - upload.received.size} 块没有收到。`,
        { received: upload.received.size, total: upload.chunks },
      );
    }
    const digest = createHash('sha256');
    let total = 0;
    for (let index = 0; index < upload.chunks; index += 1) {
      const buffer = readFileSync(partPath(upload.groupId, fileId, index));
      total += buffer.length;
      digest.update(buffer);
    }
    if (total !== upload.size) {
      discard(upload, fileId);
      throw fileError('size_mismatch', `收到的字节数与声明不符：声明 ${upload.size}，实际 ${total}。`, { declared: upload.size, actual: total });
    }
    const actual = digest.digest('hex');
    if (actual !== upload.sha256) {
      discard(upload, fileId);
      throw fileError('digest_mismatch', 'sha256 校验失败，文件在传输中损坏或被改动。', { declared: upload.sha256, actual });
    }

    ensure(groupDirectory(upload.groupId));
    const target = objectPath(upload.groupId, fileId);
    // Assemble into a temporary object and rename: a reader must never see a half-written file
    // under its final name. The rename is the publish step, and it is atomic on one filesystem.
    const assembling = `${target}.assembling`;
    await new Promise((resolve, reject) => {
      const sink = createWriteStream(assembling, { mode: 0o600 });
      sink.on('error', reject);
      sink.on('close', resolve);
      for (let index = 0; index < upload.chunks; index += 1) {
        sink.write(readFileSync(partPath(upload.groupId, fileId, index)));
      }
      sink.end();
    });
    renameSync(assembling, target);
    for (let index = 0; index < upload.chunks; index += 1) {
      rmSync(partPath(upload.groupId, fileId, index), { force: true });
    }
    pending.delete(fileId);
    logger?.info?.('file published', { groupId: upload.groupId, fileId, size: upload.size });
    return {
      fileId,
      name: upload.name,
      size: upload.size,
      sha256: actual,
      mime: upload.mime,
      uploadedBy: upload.uploadedBy,
      at: now(),
      groupId: upload.groupId,
    };
  }

  /** Read one chunk of a published file, for a downloader. */
  async function readChunk(input = {}) {
    const groupId = sealSegment(input.groupId);
    const fileId = String(input.fileId ?? '');
    if (!isFileId(fileId)) throw fileError('file_unknown', '文件不存在。');
    const path = objectPath(groupId, fileId);
    if (!existsSync(path)) throw fileError('file_unknown', '文件不存在。');
    const size = statSync(path).size;
    const chunks = Math.max(1, Math.ceil(size / MAX_CHUNK_BYTES));
    const index = input.index === undefined ? 0 : Number(input.index);
    if (!Number.isInteger(index) || index < 0 || index >= chunks) {
      throw fileError('bad_chunk_index', `分块序号必须在 0..${chunks - 1} 之间。`, { index, chunks });
    }
    const start = index * MAX_CHUNK_BYTES;
    const end = Math.min(size, start + MAX_CHUNK_BYTES);
    const buffer = Buffer.alloc(end - start);
    const handle = createReadStream(path, { start, end: end - 1 });
    return new Promise((resolve, reject) => {
      let offset = 0;
      handle.on('data', (chunk) => {
        chunk.copy(buffer, offset);
        offset += chunk.length;
      });
      handle.on('end', () => resolve({ fileId, index, chunks, size, data: buffer.toString('base64') }));
      handle.on('error', reject);
    });
  }

  /** Remove an unpublished upload's parts and forget it. */
  function discard(upload, fileId) {
    pending.delete(fileId);
    for (const index of upload.received) {
      rmSync(partPath(upload.groupId, fileId, index), { force: true });
    }
  }

  /** Delete one published file. */
  function remove(groupId, fileId) {
    if (!isFileId(fileId)) return false;
    const path = objectPath(sealSegment(groupId), fileId);
    if (!existsSync(path)) return false;
    rmSync(path, { force: true });
    return true;
  }

  /** Whether a published file is present. */
  function has(groupId, fileId) {
    if (!isFileId(fileId)) return false;
    return existsSync(objectPath(sealSegment(groupId), fileId));
  }

  /**
   * Drop staging parts older than `before`.
   *
   * Uploads abandoned halfway are the normal failure (a member closes the laptop). Without this
   * they accumulate in `.staging` forever, because nothing else ever looks in that directory.
   */
  function sweepStaging(before) {
    if (!existsSync(root)) return 0;
    let removed = 0;
    for (const entry of readdirSync(root, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue;
      const staging = join(root, entry.name, '.staging');
      if (!existsSync(staging)) continue;
      for (const part of readdirSync(staging)) {
        const path = join(staging, part);
        try {
          if (statSync(path).mtimeMs < before) {
            rmSync(path, { force: true });
            removed += 1;
          }
        } catch {
          // Vanished mid-sweep.
        }
      }
    }
    return removed;
  }

  /** Test/diagnostic view of in-flight uploads. */
  function pendingCount() {
    return pending.size;
  }

  return {
    root,
    usage,
    beginUpload,
    putChunk,
    finishUpload,
    readChunk,
    remove,
    has,
    sweepStaging,
    pendingCount,
    MAX_FILE_BYTES,
    MAX_GROUP_FILE_BYTES,
    MAX_CHUNK_BYTES,
  };
}
